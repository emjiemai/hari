def welcome(emp: Employee, manager: str | None, mentor: str | None) -> str:
    lines = [
        f"Хуш келибсиз, {emp.full_name}! Мен HARI — компаниянинг HR ёрдамчисиман, сунъий интеллектман.",
        "",
        f"Лавозимингиз: {emp.position} ({emp.department})",
    ]
    if manager:
        lines.append(f"Раҳбарингиз: {manager}")
    if mentor:
        lines.append(f"Мураббийингиз: {mentor}")
    lines += ["", "Иш, жадвал, таътил ёки қоидалар бўйича нима савол бўлса, шу ерга ёзаверинг. Ҳар куни эрталаб "
              "нима қилиш кераклигини ўзим айтиб тураман. Ишга олиш ва пул масалаларини мен эмас, масъул одам ҳал "
              "қилади."]
    return "\n".join(lines)


