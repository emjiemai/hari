def t(lang: str, key: str, **kw: object) -> str:
    texts = TEXTS[key]
    if lang == "ru":
        text = texts["ru"]
    else:
        text = texts["uz_cyrl"]
        if lang == "uz_latn" and key != "choose_lang":
            text = cyrillic_to_latin(text)
    return text.format(**kw) if kw else text


