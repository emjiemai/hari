_BY_ID = {q.qid: q for q in BANK}


def by_id(qid: str) -> LogicQuestion:
    return _BY_ID[qid]


def _lang(lang: str) -> str:
    return "ru" if lang == "ru" else "uz_cyrl"


def question_text(q: LogicQuestion, lang: str) -> str:
    text = q.text[_lang(lang)]
    return cyrillic_to_latin(text) if lang == "uz_latn" else text


def option_labels(q: LogicQuestion, lang: str) -> tuple[str, ...]:
    opts = q.options[_lang(lang)]
    return tuple(cyrillic_to_latin(o) for o in opts) if lang == "uz_latn" else opts
