"""Turn the 150 question-and-answer scenarios into knowledge documents HARI can search.

    python -m scripts.import_scenarios "HARI_150_Savol_Javob_IT_Qollanma_UZ.docx"

Reads the Word file (chapters 1–30, HARI-001 … HARI-150) and writes one markdown document per
chapter into knowledge/samples/ (HARI-QA-01.md … HARI-QA-30.md). Each scenario becomes its own
section: the employee's question is the heading, HARI's approved answer is the text. The «IT:»
notes are for developers and are left out (the scenario file says they are never shown to staff).

Answers with {{placeholders}} need data HARI is not connected to yet (МИЯ tasks, names, scores).
The placeholder is replaced by a plain phrase and the section says so, so the model explains the
general rule and never invents the missing value.

Run it again whenever the Word file changes: a changed file gets a new version number by itself
only if you raise VERSION below; the loader replaces the old text either way.
"""

from __future__ import annotations

import argparse
import re
import sys
import zipfile
from pathlib import Path

VERSION = "1"
OUT_DIR = Path("knowledge/samples")
LAST_CHAPTER = 30  # chapters 31–37 are routing tables, test plans and message templates, not scenarios
# Chapters meant for the developers, not for every employee
ROLE_ONLY = {29: "it_admin,owner"}

MISSING = "(аниқ маълумот ҳали уланмаган)"
# Kept short and free of topic words: it repeats in many sections and must not pull searches towards them.
MISSING_NOTE = "Эслатма: қавс ичида кўрсатилган маълумот ҳали HARIга уланмаган; уни масъул инсон беради."

_CHAPTER = re.compile(r"^(\d{1,2}) (\S.*)$")
_QUESTION = re.compile(r"^HARI-(\d{3})\s+(\S.*)$")
_PLACEHOLDER = re.compile(r"\{\{\s*[^}]*\}\}")


def paragraphs(docx: Path) -> list[str]:
    xml = zipfile.ZipFile(docx).read("word/document.xml").decode("utf-8")
    out = []
    for para in re.findall(r"<w:p[ >].*?</w:p>", xml, re.S):
        text = "".join(re.findall(r"<w:t[^>]*>([^<]*)</w:t>", para))
        text = (text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
                .replace("&quot;", '"').replace("&apos;", "'"))
        if text.strip():
            out.append(text.strip())
    return out


def parse(lines: list[str]) -> list[tuple[int, str, list[tuple[str, str, str]]]]:
    """[(chapter number, chapter title, [(scenario id, question, answer)])] for chapters 1..LAST_CHAPTER."""
    chapters: list[tuple[int, str, list[tuple[str, str, str]]]] = []
    question: tuple[str, str] | None = None
    for line in lines:
        chap = _CHAPTER.match(line)
        if chap and not _QUESTION.match(line):
            number = int(chap.group(1))
            if chapters and number != chapters[-1][0] + 1:
                continue  # a numbered line inside the text, not the next chapter
            if not chapters and number != 1:
                continue
            if number > LAST_CHAPTER:
                break
            chapters.append((number, chap.group(2).strip(), []))
            question = None
            continue
        q = _QUESTION.match(line)
        if q and chapters:
            question = (f"HARI-{q.group(1)}", q.group(2).strip())
            continue
        if line.startswith("HARI:") and question and chapters:
            chapters[-1][2].append((question[0], question[1], line[len("HARI:"):].strip()))
            question = None
    return chapters


def render(number: int, title: str, items: list[tuple[str, str, str]]) -> str:
    roles = ROLE_ONLY.get(number)
    head = [
        "---",
        "# Generated by scripts/import_scenarios.py from the 150-scenario guide "
        f"({items[0][0]} … {items[-1][0]}). Edit the Word file, then run the script again.",
        f"doc_id: HARI-QA-{number:02d}",
        f'title: "НАМУНА: Савол-жавоб — {title}"',
        f'version: "{VERSION}"',
        "status: approved",
        f"classification: {'role' if roles else 'internal'}",
    ]
    if roles:
        head.append(f'roles: "{roles}"')
    head += [
        "effective_from: 2026-11-01",
        "owner: HR",
        'approved_by: "НАМУНА — ҳали тасдиқланмаган"',
        "review_at: 2027-05-01",
        "---",
        "",
    ]
    body = []
    for _sid, question, answer in items:
        has_gap = bool(_PLACEHOLDER.search(answer))
        answer = re.sub(r"\s+([.,;:])", r"\1", _PLACEHOLDER.sub(MISSING, answer))
        body += [f"## {question}", "", answer, ""]
        if has_gap:
            body += [MISSING_NOTE, ""]
    return "\n".join(head + body)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("docx", type=Path, help="HARI_150_Savol_Javob_IT_Qollanma_UZ.docx")
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    args = parser.parse_args()

    chapters = parse(paragraphs(args.docx))
    total = sum(len(items) for _, _, items in chapters)
    if len(chapters) != LAST_CHAPTER or total != 150:
        raise SystemExit(f"Expected 30 chapters and 150 scenarios, found {len(chapters)} and {total}. Nothing written.")
    args.out.mkdir(parents=True, exist_ok=True)
    for number, title, items in chapters:
        (args.out / f"HARI-QA-{number:02d}.md").write_text(render(number, title, items), encoding="utf-8")
    print(f"Wrote {len(chapters)} documents with {total} scenarios to {args.out}")


if __name__ == "__main__":
    main()
